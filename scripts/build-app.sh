#!/bin/bash
# Build dist/BooxSync.app from the Swift package (no Xcode needed).
# Bundles adb (universal, system libraries only) so the app works without Homebrew.
# Usage: scripts/build-app.sh [--adb /path/to/adb] [--no-bundle-adb]
# Environment (all optional, used by the release workflow):
#   BOOXSYNC_VERSION         marketing version for Info.plist (default: the VERSION file)
#   BOOXSYNC_BUILD           build number for Info.plist (default 1)
#   BOOXSYNC_SIGN_IDENTITY   codesign identity name or hash (default: the local certificate, else ad-hoc)
#   BOOXSYNC_CHANNEL         "dev" (default): bundle id dev.booxsync.app.dev, name "BooxSync Dev", badged icon
#                            "release": bundle id dev.booxsync.app, name "BooxSync" (what the release workflow builds)
# Separate ids matter because macOS ties Screen Recording, Accessibility and Automation permissions to the
# bundle id and signature, so a local dev build and an installed release would otherwise fight over them.
set -euo pipefail
cd "$(dirname "$0")/.."

ADB_SRC=$(command -v adb || true)
while [ $# -gt 0 ]; do
  case "$1" in
    --adb) ADB_SRC=$2; shift 2 ;;
    --no-bundle-adb) ADB_SRC=""; shift ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done

CHANNEL=${BOOXSYNC_CHANNEL:-dev}
case "$CHANNEL" in
  release) BUNDLE_ID="dev.booxsync.app"; APP_NAME="BooxSync"; ICON="Resources/AppIcon.icns" ;;
  dev) BUNDLE_ID="dev.booxsync.app.dev"; APP_NAME="BooxSync Dev"; ICON="Resources/AppIcon-dev.icns" ;;
  *) echo "BOOXSYNC_CHANNEL must be dev or release" >&2; exit 1 ;;
esac
VERSION=${BOOXSYNC_VERSION:-$(tr -d '[:space:]' < VERSION)}
BUILD=${BOOXSYNC_BUILD:-1}

# Prefer an identity from the environment (CI), then the stable local certificate (scripts/setup-signing.sh) so
# macOS permissions survive rebuilds, then fall back to an ad-hoc signature.
SIGN_ID=${BOOXSYNC_SIGN_IDENTITY:-$(security find-identity -p codesigning | awk '/BooxSync Local Signing/ {print $2; exit}')}
if [ -z "$SIGN_ID" ]; then
  SIGN_ID="-"
  echo "No local signing certificate: using an ad-hoc signature (permissions reset on every build). Run scripts/setup-signing.sh."
fi

swift build -c release
BIN=$(swift build -c release --show-bin-path)/BooxSync

APP=dist/BooxSync.app
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN" "$APP/Contents/MacOS/BooxSync"
# App icon: generated by scripts/make-icon.swift.
[ -f "$ICON" ] && cp "$ICON" "$APP/Contents/Resources/AppIcon.icns"
if [ -n "$ADB_SRC" ]; then
  ADB_REAL=$(python3 -c 'import os,sys;print(os.path.realpath(sys.argv[1]))' "$ADB_SRC")
  cp "$ADB_REAL" "$APP/Contents/Resources/adb"
  mkdir -p "$APP/Contents/Resources/licenses"
  NOTICE="$(dirname "$ADB_REAL")/NOTICE.txt"
  [ -f "$NOTICE" ] && cp "$NOTICE" "$APP/Contents/Resources/licenses/android-platform-tools-NOTICE.txt"
  codesign --force --sign "$SIGN_ID" "$APP/Contents/Resources/adb"
  echo "Bundled adb: $("$APP/Contents/Resources/adb" version | head -1)"
else
  echo "adb not bundled; the app will look for adb on this Mac"
fi

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${APP_NAME}</string>
  <key>CFBundleDisplayName</key><string>${APP_NAME}</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundleExecutable</key><string>BooxSync</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>${VERSION}</string>
  <key>CFBundleVersion</key><string>${BUILD}</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSRemindersFullAccessUsageDescription</key><string>BooxSync shows your open reminders in the Boox dashboard to-do widget.</string>
  <key>NSRemindersUsageDescription</key><string>BooxSync shows your open reminders in the Boox dashboard to-do widget.</string>
  <key>NSAppleEventsUsageDescription</key><string>BooxSync reads the current track from Spotify or Music to show it on the Boox dashboard.</string>
</dict>
</plist>
PLIST

codesign --force --sign "$SIGN_ID" "$APP"
echo "Built $APP ($APP_NAME, $BUNDLE_ID, version $VERSION)"
